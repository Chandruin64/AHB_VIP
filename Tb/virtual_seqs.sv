//------------------------------------------------------------------------------
// Base Virtual Sequence
//------------------------------------------------------------------------------

class virtual_seqs extends uvm_sequence#(uvm_sequence_item);

    `uvm_object_utils(virtual_seqs)


    //--------------------------------------------------------------------------
    // Sequencer Handles
    //--------------------------------------------------------------------------

    virtual_sequencer vseqr;
    mst_sequencer     mst_seqr;


    //--------------------------------------------------------------------------
    // Constructor
    //--------------------------------------------------------------------------

    function new(string name = "virtual_seqs");
        super.new(name);
    endfunction


    //--------------------------------------------------------------------------
    // Body
    //--------------------------------------------------------------------------

    task body();

        if (!$cast(vseqr, m_sequencer))
            `uvm_fatal(
                "VIRTUAL SEQUENCER CONFIG",
                "FAILED"
            )

        mst_seqr = vseqr.mst_seqr;

    endtask

endclass


//------------------------------------------------------------------------------
// Single Transfer Virtual Sequence
//------------------------------------------------------------------------------

class single_vseq extends virtual_seqs;

    `uvm_object_utils(single_vseq)


    //--------------------------------------------------------------------------
    // Master Sequence
    //--------------------------------------------------------------------------

    mst_single_seq mst;


    //--------------------------------------------------------------------------
    // Constructor
    //--------------------------------------------------------------------------

    function new(string name = "single_vseq");
        super.new(name);
    endfunction


    //--------------------------------------------------------------------------
    // Body
    //--------------------------------------------------------------------------

    task body();

        super.body();

        repeat (1) begin
            mst = mst_single_seq::type_id::create("mst");
            mst.start(mst_seqr);
        end

    endtask

endclass


